#!/usr/bin/env node
'use strict'
// Execute the real outcome recorder with synthetic responses; never load app
// secrets, a provider client, account data, microphone or database.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const crypto = require('node:crypto')
const file = path.join(__dirname, '../lib/native-voice-action-observability.ts')
const source = fs.readFileSync(file, 'utf8')
const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true)
const printer = ts.createPrinter()
const stripped = ast.statements.filter(node => !ts.isImportDeclaration(node)).map(node => printer.printNode(ts.EmitHint.Unspecified, node, ast)).join('\n').replace(/^export\s+/gm, '')
const events = [], logs = []
const ctx = vm.createContext({ crypto, Date, Headers, Response, console: { info: (...args) => logs.push(args) }, NextResponse: { json: (data, init) => Response.json(data, init) }, logAiUsageEvent: async event => events.push(event) })
vm.runInContext(ts.transpileModule(stripped, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText, ctx)
async function run() {
  const outcome = (data, status = 200, phase = 'prepare') => ctx.voiceActionOutcome(data, status, phase)
  assert.equal(outcome({ success: true, draft: { action: 'food_draft', canConfirm: false } }).status, 'needs_clarification')
  assert.equal(outcome({ success: true, draft: { action: 'food_draft', canConfirm: false } }).success, false)
  for (const reasonCode of ['food_amount_ambiguous', 'food_source_unavailable', 'food_serving_unavailable']) assert.equal(outcome({ success: true, draft: { action: 'food_draft', canConfirm: false, reasonCode } }).reasonCode, reasonCode)
  assert.equal(outcome({ success: true, draft: { action: 'food_draft', canConfirm: false, reasonCode: 'private_health_text' } }).reasonCode, 'action_details_unresolved')
  assert.equal(outcome({ success: true, draft: { action: 'water', canConfirm: true } }).status, 'needs_review')
  assert.equal(outcome({ success: true, confirmNow: true }).status, 'confirmation_requested')
  assert.equal(outcome({ success: true, rejectNow: true }).status, 'discarded')
  assert.equal(outcome({ success: true, draft: { action: 'mood', canConfirm: false } }).status, 'needs_clarification')
  assert.equal(outcome({ success: true, draft: { action: 'recipe', recipe: { text: 'Synthetic' } } }).status, 'answered')
  assert.equal(outcome({ success: true, draft: { action: 'app_handoff', appTarget: { title: 'Synthetic' } } }).status, 'handoff_ready')
  assert.equal(outcome({ success: true }, 200, 'save').success, false)
  assert.equal(outcome({ success: true, result: { kind: 'food', message: 'Saved' } }, 200, 'save').success, false)
  assert.equal(outcome({ success: true, result: { kind: 'food', ids: ['synthetic'], message: 'Saved' } }, 200, 'save').status, 'saved')
  assert.equal(outcome({ success: true, result: { kind: 'recipe_import', status: 'imported_not_saved', saved: false, actionId: 'synthetic', nextRecipeDraft: { action: 'recipe', canConfirm: false } } }, 200, 'save').status, 'imported_for_review')
  assert.equal(outcome({ success: true, result: { kind: 'recipe_import', status: 'imported_not_saved', saved: false } }, 200, 'save').success, false)
  assert.equal(outcome({ success: true, result: { kind: 'report_action', action: 'reports.weekly.generate', status: 'preparing', actionId: 'synthetic', reportId: 'report-synthetic', reportStatus: 'RUNNING', generated: false, unlocked: false } }, 200, 'save').status, 'report_request_recorded')
  assert.equal(outcome({ success: true, result: { kind: 'report_action', status: 'ready', reportId: 'synthetic' } }, 200, 'save').success, false)
  assert.equal(outcome({ success: true, draft: { action: 'health_question', canConfirm: false, reasonCode: 'app_read_unverified' } }).success, false)
  assert.equal(outcome({ success: true, draft: { action: 'greeting', canConfirm: false } }).status, 'answered')
  assert.equal(outcome({ error: 'Synthetic private error' }, 500).reasonCode, 'http_500')
  const trace = ctx.beginVoiceActionTrace({ headers: new Headers({ 'x-helfi-voice-action-id': 'synthetic-action-123' }) }, 'prepare')
  trace.userId = 'synthetic-user'
  const response = await ctx.finishVoiceActionTrace(Response.json({ success: true, transcript: 'PRIVATE_SYNTHETIC_SPEECH', draft: { action: 'food_draft', canConfirm: false, reviewToken: 'PRIVATE_SYNTHETIC_TOKEN' } }), trace)
  const result = await response.json()
  assert.equal(result.voiceActionRunId, 'synthetic-action-123')
  assert.equal(response.headers.get('x-helfi-voice-action-id'), 'synthetic-action-123')
  assert.equal(events[0].success, false)
  assert.equal(events[0].costCents, 0)
  assert.equal(events[0].runId, 'synthetic-action-123')
  assert.equal(events[0].feature, 'voice-action:prepare-outcome')
  assert(!JSON.stringify({ logs, events }).includes('PRIVATE_SYNTHETIC'))
  const saveTrace = ctx.beginVoiceActionTrace({ headers: new Headers() }, 'save')
  saveTrace.userId = 'synthetic-user'; saveTrace.action = 'record_action'
  await ctx.finishVoiceActionTrace(Response.json({error:'PRIVATE_SYNTHETIC_DETAILS',code:'drink_update_failed'},{status:500}),saveTrace)
  const failed = JSON.parse(events[1].detail)
  assert.equal(failed.action,'record_action'); assert.equal(failed.reasonCode,'drink_update_failed'); assert.equal(failed.success,false)
  assert(!JSON.stringify({logs,events}).includes('PRIVATE_SYNTHETIC'))
  const generated = ctx.beginVoiceActionTrace({ headers: new Headers({ 'x-helfi-voice-action-id': 'bad value' }) }, 'save')
  assert.match(generated.id, /^[a-f0-9-]{36}$/)
  console.log('PASS actual outcome logging: clarification differs from review/save, malformed save receipts fail, safe correlation survives, and speech/tokens never enter trace/usage records. Offline synthetic responses only.')
}
run().catch(error => { console.error(error); process.exitCode = 1 })
